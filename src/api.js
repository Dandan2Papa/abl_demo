// ─── Main API Function ───────────────────────────────────────────────────────
export async function callLLM({ messages, system, settings }) {
  // Demo mode: no API key → return sample response
  if (!settings?.apiKey) {
    await new Promise(r => setTimeout(r, 800 + Math.random() * 600)); // realistic delay
    const { text } = getDemoResponse(messages);
    return text;
  }

  const headers = {
    "Content-Type": "application/json",
    "anthropic-version": "2023-06-01",
    "x-api-key": settings.apiKey,
    "anthropic-dangerous-direct-browser-access": "true",
  };

  const res = await fetch(settings.apiUrl || "https://api.anthropic.com/v1/messages", {
    method: "POST",
    headers,
    body: JSON.stringify({
      model: settings.model || "claude-sonnet-4-20250514",
      max_tokens: 1200,
      system: system || "당신은 보험업 전문 AI 어시스턴트입니다.",
      messages: messages.filter(m => m.role !== "system"),
    }),
  });

  const data = await res.json();
  if (data.error) throw new Error(data.error.message || JSON.stringify(data.error));
  return data.content.find((b) => b.type === "text")?.text || "";
}

