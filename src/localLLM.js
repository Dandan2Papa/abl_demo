export async function callLocalLLM({ messages, system }) {
  // Simulate realistic latency (1.2~2.4s)
  await delay(1200 + Math.random() * 1200);

  const lastUser = [...messages].reverse().find((m) => m.role === "user");
  const userText = lastUser?.content || "";

  // 1. Rider tip (AI 고객 접근 멘트)
  if (system.includes("FC가 고객에게 보장 부족을 설명")) {
    const diseaseMatch = userText.match(/보장 부족 항목:\s*([^\n]+)/);
    const label = diseaseMatch?.[1]?.trim() || "";
    const idMap = { 암진단: "cancer", 뇌혈관진단: "brain", 심장혈관진단: "heart", 골절진단: "bone", 실화손단: "liver", 수술비: "surgery", 사망: "death" };
    const id = Object.keys(idMap).find((k) => label.includes(k));
    const pool = RIDER_TIPS[idMap[id] || "cancer"] || RIDER_TIPS.cancer;
    return pool[Math.floor(Math.random() * pool.length)];
  }

  // 2. Policy chatbot (약관 챗봇)
  if (system.includes("약관 정보를 기반으로")) {
    return matchChatbot(userText);
  }

  // 3. Sales script generation
  if (system.includes("영업 스크립트를 작성")) {
    return buildSalesScript(userText);
  }

  // 4. Platform agent — detect agent from system prompt
  for (const title of Object.keys(PLATFORM_RESPONSES)) {
    if (system.includes(title)) {
      return platformResponse(title, userText);
    }
  }

  // Fallback generic response
  return "안녕하세요. ABL생명 AI 지원 플랫폼입니다. 궁금하신 사항을 질문해 주시면 도움을 드리겠습니다.";
}
